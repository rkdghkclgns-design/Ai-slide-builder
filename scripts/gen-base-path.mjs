#!/usr/bin/env node
/**
 * Generate src/lib/base-path.ts with a hardcoded BASE_PATH constant,
 * so Next.js client bundler sees a literal string (no runtime process.env lookup).
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const basePath = process.env.GITHUB_PAGES === "true" ? "/Ai-slide-builder" : "";

const content = `// AUTO-GENERATED by scripts/gen-base-path.mjs — do not edit manually.
export const BASE_PATH = ${JSON.stringify(basePath)};

export function asset(path: string): string {
  if (!path.startsWith("/")) path = "/" + path;
  return BASE_PATH + path;
}
`;

const outPath = join(__dirname, "..", "src", "lib", "base-path.ts");
writeFileSync(outPath, content, "utf8");
console.log(`[gen-base-path] BASE_PATH="${basePath}" → ${outPath}`);
